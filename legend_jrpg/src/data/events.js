// ───────── 헬퍼 ─────────
const t = (speaker, text) => ({ cmd: 'text', speaker, text });
const n = (text) => ({ cmd: 'text', text });
const flag = (f, value = true) => ({ cmd: 'setFlag', flag: f, value });
const iff = (f, then, els = []) => ({ cmd: 'if', flag: f, then, else: els });
const ifnot = (f, then, els = []) => ({ cmd: 'if', flag: f, not: true, then, else: els });
const say = (speaker, ...lines) => lines.map((l) => t(speaker, l));
const boss = (troop, bg, bgm = 'boss') => ({ cmd: 'battle', troop, canEscape: false, bg, bgm });
const flash = (color = '#ffffff', ms = 300) => ({ cmd: 'flash', color, ms });
const shake = (ms = 400) => ({ cmd: 'shake', ms });
const bgm = (key) => ({ cmd: 'bgm', key });
const sfx = (name) => ({ cmd: 'sfx', name });
const wait = (ms) => ({ cmd: 'wait', ms });
const saveChoice = () => ({
  cmd: 'choice', text: '여정을 기록하시겠습니까?', options: ['기록한다', '그만둔다'],
  branches: [[{ cmd: 'save' }], []],
});

// 진행도별 대사: cases = [[flag, [대사...]], ...] (위에 있을수록 우선), fallback = [대사...]
function talk(speaker, cases, fallback) {
  return cases.reduceRight((acc, [f, lines]) => [iff(f, say(speaker, ...lines), acc)], say(speaker, ...fallback));
}

